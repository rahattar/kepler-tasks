"""How robust the reference is to what it cannot control: sensor noise and the instance.

    python3 authoring/evidence/reference_reseeds.py > authoring/evidence/reference_reseeds.txt

NOISE RESEEDS. The shipped hidden wafers with every wafer's sensor-noise seed redrawn, graded
with the reference controller built from the shipped data.

INSTANCE RESEEDS. The whole instance regenerated by the shipped generator under a different
seed - characterisation logs, their noise, and a new hidden set - then the reference run end
to end on it: solve.py identifies the plant from that instance's logs, writes a controller,
and the verifier grades it against that instance's own hidden set and benchmark.

Both use the shipped verifier (grade.run_wafer, sandboxed) and the gate as shipped.
"""
import contextlib
import copy
import io
import json
import os
import sys
import tempfile
import time

import numpy as np

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "tests"))
sys.path.insert(0, os.path.join(ROOT, "solution"))
sys.path.insert(0, os.path.join(ROOT, "authoring", "provenance"))
import grade  # noqa: E402
import make_data  # noqa: E402

N_NOISE = 6
INSTANCE_SEEDS = [20261101, 20261102, 20261103, 20261104, 20261105, 20261106]


def build_reference(data_dir, out_path):
    os.environ["CHILL_DATA"] = data_dir
    import importlib
    import solve
    importlib.reload(solve)          # DATA is read at import time
    with contextlib.redirect_stdout(io.StringIO()):
        stations, split, wafer, prod, runs = solve.load()
        ident = solve.identify(stations, split, wafer, prod, runs)
    solve.write_controller(ident, wafer, prod, split, out_path)
    return ident


def grade_on(path, truth, bench):
    rows = [grade.run_wafer(path, truth, w) for w in truth["wafers"]]
    tot = sum(r["cycle_s"] if r["cycle_s"] is not None else 30.0 for r in rows)
    tb = sum(bench[r["id"]] for r in rows)
    fails = [r for r in rows if not r["passed"]]
    ratio = tot / tb
    reward = int(not fails and ratio <= 1 + truth["allowance"] + grade.EPS)
    return dict(reward=reward, ratio=ratio, failed=[r["id"] for r in fails],
                worst=max(r["worst_zone_dT_K"] for r in rows),
                hottest=max((r["T_release_C"] or 0.0) for r in rows),
                why=["%s %s" % (r["id"], r["error"] or ("zone %.2f" % r["worst_zone_dT_K"]
                                                       if not r["meets_zone"] else
                                                       "release %.2f" % r["T_release_C"]))
                     for r in fails][:3])


def line(label, s):
    return ("%-34s reward %d  ratio %.3f  failed %-12s worst zone %.2f K  hottest %.2f C%s"
            % (label, s["reward"], s["ratio"], ",".join(s["failed"]) or "none", s["worst"],
               s["hottest"], ("  (" + "; ".join(s["why"]) + ")") if s["why"] else ""))


def main():
    t00 = time.time()
    work = tempfile.mkdtemp(prefix="wcc_reseeds_")
    shipped = grade.load_truth()
    ref = os.path.join(work, "reference.py")
    build_reference(os.path.join(ROOT, "environment", "data"), ref)
    b = grade.benchmarks(shipped)
    bench = {k: v[0] for k, v in b.items()}

    print("NOISE RESEEDS: shipped hidden set, every wafer's noise seed redrawn")
    s = grade_on(ref, shipped, bench)
    print(line("shipped noise seeds", s), flush=True)
    passes = s["reward"]
    rng = np.random.default_rng(7)
    for i in range(N_NOISE):
        tr = copy.deepcopy(shipped)
        for w in tr["wafers"]:
            w["_noise_seed"] = int(rng.integers(1, 2**31 - 1))
        s = grade_on(ref, tr, bench)
        passes += s["reward"]
        print(line("noise draw %d" % (i + 1), s), flush=True)
    print("-> %d of %d pass\n" % (passes, N_NOISE + 1))

    print("INSTANCE RESEEDS: generator rerun under a new seed, reference run end to end")
    passes = 0
    for seed in INSTANCE_SEEDS:
        make_data.SEED = seed
        files, truth = make_data.build()
        d = os.path.join(work, "data_%d" % seed)
        make_data.emit_data(files, d)
        path = os.path.join(work, "ref_%d.py" % seed)
        t0 = time.time()
        ident = build_reference(d, path)
        b = grade.benchmarks(truth)
        bench_i = {k: v[0] for k, v in b.items()}
        s = grade_on(path, truth, bench_i)
        passes += s["reward"]
        print(line("seed %d (fit rms %.2f)" % (seed, ident["rms"]), s)
              + "  [%.0f s]" % (time.time() - t0), flush=True)
    print("-> %d of %d pass" % (passes, len(INSTANCE_SEEDS)))
    print("\n[%.0f s]" % (time.time() - t00))


if __name__ == "__main__":
    main()
